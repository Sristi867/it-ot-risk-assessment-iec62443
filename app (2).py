# Load the file into a table and look at it
import pandas as pd

df = pd.read_csv("Simulated_IT-OT_Plant_Network_Risk_Assessment_scored (1).csv")
print(df.shape)
df.head()

# Work out the four numbers for the top cards
total_findings = len(df)
critical_count = (df["risk_level"] == "Critical").sum()
open_paths = (df["segmentation_status"] == "Open path").sum()
total_cost_crore = df["remediation_cost_inr"].sum() / 10_000_000

print("Findings:", total_findings)
print("Critical:", critical_count)
print("Open paths:", open_paths)
print(f"Total fix cost: Rs {total_cost_crore:.2f} crore")

# Work out the average risk score for each zone
zone_risk = df.groupby("zone")["risk_score"].mean().round(1).sort_values(ascending=False)
print(zone_risk)

# Draw the average risk by zone as a bar chart
import plotly.express as px

zone_df = zone_risk.reset_index()
fig = px.bar(zone_df, x="zone", y="risk_score",
             title="Average risk score by zone",
             labels={"risk_score": "Average risk score", "zone": "Zone"})
fig.show()

# Keep only the open path findings and count them by start zone and destination
open_df = df[df["segmentation_status"] == "Open path"]
paths = open_df.groupby(["exposure_path", "zone"]).size().reset_index(name="findings")
print(len(open_df))
paths

# Draw the open paths as a stacked horizontal bar chart
import plotly.express as px

order = paths.groupby("exposure_path")["findings"].sum().sort_values().index.tolist()
fig2 = px.bar(paths, x="findings", y="exposure_path", color="zone", orientation="h",
              category_orders={"exposure_path": order},
              title="Open paths: where they lead, and which zone they start from",
              labels={"exposure_path": "Where the path leads",
                      "findings": "Number of findings",
                      "zone": "Device zone"})
fig2.show()

# Add a cost column in lakh rupees and draw cost against risk
df["cost_lakh"] = df["remediation_cost_inr"] / 100_000

fig3 = px.scatter(df, x="cost_lakh", y="risk_score", color="operational_criticality",
                  hover_name="asset_name",
                  hover_data={"remediation_action": True, "zone": True, "cost_lakh": ":.1f"},
                  category_orders={"operational_criticality": ["Critical", "High", "Medium", "Low"]},
                  labels={"cost_lakh": "Cost of fix (Rs lakh)", "risk_score": "Risk score",
                          "operational_criticality": "Criticality"})
fig3.show()

# Rank the fixes: highest risk first, cheapest first when risk is tied
